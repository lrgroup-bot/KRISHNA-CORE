"""Durable six-hour curriculum and paired-device mission contract tests."""
from __future__ import annotations

import json
from pathlib import Path
import tempfile
import unittest

from krishna_core.suryadev_mission_backlog import SuryadevMissionBacklog, CATALOG_SCHEMA
from krishna_core.remote_access import PrivateRemotePolicy
from krishna_core.suryadev import SuryadevAgent


def approved_catalogue():
    return {
        "schema": CATALOG_SCHEMA,
        "allowed_source_hosts": ["docs.python.org", "playwright.dev"],
        "missions": [
            {"id": "python-async", "topic": "Asyncio lifecycle and cancellation",
             "approved_urls": ["https://docs.python.org/3/library/asyncio-task.html"]},
            {"id": "python-network", "topic": "Python safe HTTP clients",
             "approved_urls": ["https://docs.python.org/3/howto/urllib2.html"]},
            {"id": "browser-testing", "topic": "Playwright browser automation",
             "approved_urls": ["https://playwright.dev/python/docs/intro"]},
        ],
    }


class SuryadevMissionBacklogTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.planner = SuryadevMissionBacklog(self.root)
        (self.root / "approved-curriculum.json").write_text(
            json.dumps(approved_catalogue()), encoding="utf-8")

    def tearDown(self):
        self.temp.cleanup()

    def request(self, value):
        return {"request_id": value * 32, "desired_hours": 6}

    def test_ready_has_two_staged_missions_and_refills_after_offer(self):
        status = self.planner.status()
        self.assertEqual(status["prepared"], 2)
        self.assertFalse(status["guarantees_six_hours_of_unique_content"])
        first = self.planner.offer(self.request("a"), device_id="suryadev-laptop")
        self.assertEqual(first["status"], "offered")
        self.assertEqual(first["mission"]["duration_hours"], 6)
        self.assertFalse(first["delivery_acknowledged"])
        second = self.planner.status()
        self.assertEqual(second["prepared"], 2)
        self.assertEqual(second["issued"], 1)

    def test_idempotent_offer_restart_receipt_and_eventual_exhaustion(self):
        first = self.planner.offer(self.request("a"), device_id="suryadev-laptop")
        restarted = SuryadevMissionBacklog(self.root)
        replay = restarted.offer(self.request("a"), device_id="suryadev-laptop")
        self.assertTrue(replay["replay"])
        self.assertEqual(first["mission"], replay["mission"])
        self.assertFalse(replay["delivery_acknowledged"])
        with self.assertRaises(PermissionError):
            restarted.offer(self.request("a"), device_id="other-device")
        no_source = restarted.acknowledge(request_id="a"*32,
                                         device_id="suryadev-laptop",
                                         accepted=False, queued_urls=0)
        self.assertFalse(no_source["acknowledged"])
        ack = restarted.acknowledge(request_id="a"*32, device_id="suryadev-laptop",
                                   accepted=True, queued_urls=1)
        self.assertTrue(ack["acknowledged"])
        self.assertFalse(ack["knowledge_accepted"])
        self.assertFalse(ack["brahmagyan_acknowledged"])
        self.assertTrue(restarted.acknowledge(
            request_id="a"*32, device_id="suryadev-laptop",
            accepted=True, queued_urls=1)["idempotent"])
        self.assertEqual(restarted.offer(self.request("b"), device_id="suryadev-laptop")["status"],
                         "offered")
        self.assertEqual(restarted.offer(self.request("c"), device_id="suryadev-laptop")["status"],
                         "offered")
        exhausted = restarted.offer(self.request("d"), device_id="suryadev-laptop")
        self.assertEqual(exhausted["status"], "no_approved_work")
        self.assertFalse(exhausted["delivery_acknowledged"])

    def test_unauthorized_and_corrupt_catalogue_fail_closed(self):
        for value in ("not-a-uuid", None):
            with self.assertRaises(ValueError):
                self.planner.offer({"request_id": value, "desired_hours": 6},
                                   device_id="suryadev-laptop")
        with self.assertRaises(ValueError):
            self.planner.offer({"request_id": "a"*32, "desired_hours": 2},
                               device_id="suryadev-laptop")
        path = self.root / "approved-curriculum.json"
        catalogue = approved_catalogue()
        catalogue["missions"][0]["approved_urls"] = ["http://127.0.0.1/internal"]
        path.write_text(json.dumps(catalogue), encoding="utf-8")
        with self.assertRaises(ValueError):
            self.planner.status()

    def test_no_catalogue_is_truthful_not_autogenerated(self):
        (self.root / "approved-curriculum.json").unlink()
        status = self.planner.status()
        self.assertEqual(status["prepared"], 0)
        self.assertIn("missing", status["source_policy"])
        res = self.planner.offer(self.request("f"), device_id="suryadev-laptop")
        self.assertEqual(res["status"], "no_approved_work")

    def test_core_agent_reuses_existing_krishna_authority(self):
        core = SuryadevAgent(self.root / "core")
        catalog = core.mission_backlog.catalogue
        catalog.write_text(json.dumps(approved_catalogue()), encoding="utf-8")
        status = core.status()
        self.assertEqual(status["mission_backlog"]["prepared"], 2)
        packet = core.mission_offer(self.request("e"), device_id="suryadev-laptop")
        self.assertEqual(packet["mission"]["id"], "python-async")
        receipt = core.mission_acknowledge(
            {"request_id": "e"*32, "accepted": True, "queued_urls": 1},
            device_id="suryadev-laptop")
        self.assertTrue(receipt["acknowledged"])
        self.assertFalse(receipt["knowledge_accepted"])

    def test_remote_routes_restricted_to_paired_device(self):
        policy = PrivateRemotePolicy()
        self.assertTrue(policy.mobile_route_allowed("/api/suryadev/mission/request"))
        self.assertTrue(policy.mobile_route_allowed("/api/suryadev/mission/ack"))
        self.assertFalse(policy.mobile_route_allowed("/api/suryadev/mission/owner-config"))


if __name__ == "__main__":
    unittest.main()
